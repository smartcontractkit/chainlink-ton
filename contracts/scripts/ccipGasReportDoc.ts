// Merges the snapshots written by the CCIP gas-report specs into a markdown document with the
// worst-case cost per CCIP entrypoint. Run `yarn ccip-gas-report` first.
//
//   yarn ccip-gas-report:md [--network mainnet|testnet|default] [--out <file>]
import * as fs from 'fs'
import * as path from 'path'
import { fromNano } from '@ton/core'
import type { EntrypointCost, FlowSummary, HopSummary, Owner } from '../tests/gas-report/utils'

const SNAPSHOT_DIR = path.join(__dirname, '..', 'tests', 'gas-report', 'ccip', 'snapshots')
const DEFAULT_OUT = path.join(
  __dirname,
  '..',
  '..',
  'docs',
  'contracts',
  'overview',
  'ccip',
  'gas-report.md',
)
const SAFETY_FACTOR = 5n
const OWNERS: Owner[] = ['ccip', 'registry', 'token', 'external']

type Snapshot = { network: string; gasPrice: bigint; flows: FlowSummary[] }

type Breakdown = { compute: bigint; forward: bigint; storage: bigint }

type WorstCase = {
  contract: string
  op: string
  flow: string
  spec: string
  cost: Record<Owner, bigint>
  ccip: Breakdown
}

function arg(name: string, fallback: string): string {
  const i = process.argv.indexOf(`--${name}`)
  return i >= 0 && process.argv[i + 1] ? process.argv[i + 1] : fallback
}

// JSON.parse leaves bigints as strings; convert the numeric fields back.
function revive(key: string, value: unknown): unknown {
  if (
    typeof value === 'string' &&
    /^-?\d+$/.test(value) &&
    !['label', 'from', 'to', 'op', 'contract', 'owner', 'network'].includes(key)
  ) {
    return BigInt(value)
  }
  return value
}

function loadSnapshots(network: string): Map<string, Snapshot> {
  const out = new Map<string, Snapshot>()
  if (!fs.existsSync(SNAPSHOT_DIR)) return out
  for (const file of fs.readdirSync(SNAPSHOT_DIR).sort()) {
    const match = file.match(/^(.*)\.([a-z]+)\.json$/)
    if (!match || match[2] !== network) continue
    out.set(match[1], JSON.parse(fs.readFileSync(path.join(SNAPSHOT_DIR, file), 'utf8'), revive))
  }
  return out
}

function ccipBreakdown(hops: HopSummary[], root: number): Breakdown {
  const out: Breakdown = { compute: 0n, forward: 0n, storage: 0n }
  const visit = (i: number) => {
    const hop = hops[i]
    if (hop.owner === 'ccip') {
      out.compute += hop.computeFee
      out.forward += hop.forwardFee
      out.storage += hop.storageFee
    }
    hop.children.forEach(visit)
  }
  visit(root)
  return out
}

const ton = (v: bigint) => fromNano(v)
const sum = (cost: Record<Owner, bigint>) => OWNERS.reduce((s, o) => s + cost[o], 0n)
const isSweep = (flow: FlowSummary) => flow.label.startsWith('sweep:')
const code = (s: string) => `\`${s}\``

function table(headers: string[], rows: string[][]): string {
  const line = (cells: string[]) => `| ${cells.join(' | ')} |`
  return [line(headers), line(headers.map(() => '---')), ...rows.map(line)].join('\n')
}

function worstCases(snapshots: Map<string, Snapshot>): WorstCase[] {
  const worst = new Map<string, WorstCase>()
  for (const [spec, snapshot] of snapshots) {
    for (const flow of snapshot.flows) {
      if (isSweep(flow)) continue
      for (const e of flow.entrypoints as EntrypointCost[]) {
        const key = `${e.contract}\0${e.op}`
        const current = worst.get(key)
        if (!current || e.cost.ccip > current.cost.ccip) {
          worst.set(key, {
            contract: e.contract,
            op: e.op,
            flow: flow.label,
            spec,
            cost: e.cost,
            ccip: ccipBreakdown(flow.hops, e.hop),
          })
        }
      }
    }
  }
  return [...worst.values()].sort(
    (a, b) => a.contract.localeCompare(b.contract) || a.op.localeCompare(b.op),
  )
}

function render(network: string, snapshots: Map<string, Snapshot>): string {
  // Config param 21 prices gas per 2^16 units.
  const gasPrice = [...snapshots.values()][0]?.gasPrice ?? 0n
  const gasEq = (v: bigint) => (gasPrice === 0n ? '-' : ((v << 16n) / gasPrice).toString())
  const nanoPerGas = (Number(gasPrice) / 65536).toFixed(2)
  const out: string[] = []

  out.push('# CCIP gas report')
  out.push('')
  out.push(
    `Generated by \`yarn ccip-gas-report:md\` from the \`${network}\` snapshots in \`contracts/tests/gas-report/ccip/snapshots/\`. Do not edit by hand.`,
  )
  out.push('')
  out.push(
    "Each hop of a flow is attributed to the owner of the receiving contract: `ccip` (Router, ramps, executors, deposit accounts, MerkleRoot, FeeQuoter), `registry` (TokenAdminRegistry and entries), `token` (pools, lockboxes, minters, jetton wallets) or `external` (users, receivers, transmitters). A hop's cost is its storage and compute fees plus the full forward fees of the messages it sends. Registry and token hops are budgeted by their own contracts; only the `ccip` part is what the CCIP entrypoints have to cover.",
  )
  out.push('')
  out.push(`Gas price: ${nanoPerGas} nanotons per gas unit. Safety factor: ${SAFETY_FACTOR}x.`)
  out.push('')
  out.push(
    'See [value-flow.md](./value-flow.md) for how each handler currently funds the next hop.',
  )
  out.push('')

  out.push('## Worst case per CCIP entrypoint')
  out.push('')
  out.push(
    'Cost of the entrypoint transaction and everything downstream of it, taken from the flow where the `ccip` part is largest. Sweep flows are excluded.',
  )
  out.push('')
  out.push(
    table(
      [
        'Contract',
        'Entrypoint',
        'CCIP',
        'compute',
        'forward',
        'storage',
        'Registry',
        'Token',
        'Total',
        'CCIP gas eq.',
        `CCIP x${SAFETY_FACTOR}`,
        'Worst flow',
      ],
      worstCases(snapshots).map((w) => [
        w.contract,
        code(w.op),
        ton(w.cost.ccip),
        ton(w.ccip.compute),
        ton(w.ccip.forward),
        ton(w.ccip.storage),
        ton(w.cost.registry),
        ton(w.cost.token),
        ton(sum(w.cost)),
        gasEq(w.cost.ccip),
        ton(w.cost.ccip * SAFETY_FACTOR),
        `${w.spec}: ${w.flow}`,
      ]),
    ),
  )
  out.push('')

  out.push('## Cost per flow by owner')
  out.push('')
  const flowRows: string[][] = []
  for (const [spec, snapshot] of snapshots) {
    for (const flow of snapshot.flows) {
      if (isSweep(flow)) continue
      flowRows.push([
        spec,
        flow.label,
        String(flow.hops.length),
        ...OWNERS.map((o) => ton(flow.totals[o])),
        ton(sum(flow.totals)),
      ])
    }
  }
  out.push(
    table(['Spec', 'Flow', 'Hops', 'CCIP', 'Registry', 'Token', 'External', 'Total'], flowRows),
  )
  out.push('')

  out.push('## Balance changes')
  out.push('')
  out.push(
    'Value a contract keeps (positive) or spends from its own balance (negative) during a flow. These are not costs and must not be folded into min values; positive entries on CCIP contracts are value sinks to fix or refund.',
  )
  out.push('')
  const balanceRows: string[][] = []
  for (const [spec, snapshot] of snapshots) {
    for (const flow of snapshot.flows) {
      if (isSweep(flow)) continue
      const owners = new Map(flow.hops.map((hop) => [hop.to, hop.owner]))
      for (const [name, delta] of Object.entries(flow.retained)) {
        const owner = owners.get(name)
        // Storage fees show up as nanoton-level changes.
        if ((delta < 100n && delta > -100n) || owner === 'external' || owner === undefined) continue
        balanceRows.push([spec, flow.label, name, owner, ton(delta)])
      }
    }
  }
  out.push(table(['Spec', 'Flow', 'Contract', 'Owner', 'Change'], balanceRows))
  out.push('')

  out.push('## Cost by data size')
  out.push('')
  out.push(
    'Send-side flows repeated with growing `data`. The FeeQuoter rejects data over 128 cells (16256 bytes of 127-byte cells); lanes are configured with `maxDataBytes` 2000.',
  )
  out.push('')
  const sweepRows: string[][] = []
  for (const [spec, snapshot] of snapshots) {
    for (const flow of snapshot.flows) {
      if (!isSweep(flow)) continue
      const bytes = flow.label.match(/(\d+) bytes/)?.[1] ?? '?'
      sweepRows.push([
        spec,
        flow.label.replace(/^sweep: /, ''),
        bytes,
        ton(flow.totals.ccip),
        ton(sum(flow.totals)),
      ])
    }
  }
  out.push(table(['Spec', 'Flow', 'Bytes', 'CCIP', 'Total'], sweepRows))
  out.push('')
  return out.join('\n')
}

const network = arg('network', process.env['GAS_REPORT_NETWORK'] ?? 'mainnet')
const outFile = arg('out', DEFAULT_OUT)
const snapshots = loadSnapshots(network)
if (snapshots.size === 0) {
  console.error(
    `No ${network} snapshots in ${SNAPSHOT_DIR}; run GAS_REPORT_NETWORK=${network} yarn ccip-gas-report first`,
  )
  process.exit(1)
}
fs.mkdirSync(path.dirname(outFile), { recursive: true })
fs.writeFileSync(outFile, render(network, snapshots) + '\n')
console.log(`Wrote ${outFile} from ${[...snapshots.keys()].join(', ')}`)
