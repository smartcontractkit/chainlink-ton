import { runLimitsSuite } from './limits/suite'

runLimitsSuite({
  version: 'local',
  expectedVersion: '0.0.6',
  limits: {
    maxSigners: 200,
    maxGroups: 31,
    maxSignatures: 72,
    setConfigStrategy: 'staged',
  },
  cases: [
    // Direct single-step configs on current main. The iterator size validation in
    // current main makes these more expensive than older releases.
    {
      name: 'setConfig: 56 signers / 31 groups',
      op: 'setConfig',
      signers: 56,
      groups: 31,
      expected: 'success',
      maxGas: 960_000n,
    },
    {
      name: 'setConfig: 56 -> 56 signers / 31 groups',
      op: 'setConfig',
      signers: 56,
      groups: 31,
      fromSigners: 56,
      expected: 'success',
      maxGas: 970_000n,
    },
    {
      name: 'setConfig: 60 -> 60 signers / 21 groups',
      op: 'setConfig',
      signers: 60,
      groups: 21,
      fromSigners: 60,
      expected: 'success',
      maxGas: 960_000n,
    },
    {
      name: 'setConfig: 69 signers / 3 groups',
      op: 'setConfig',
      signers: 69,
      groups: 3,
      expected: 'success',
      maxGas: 900_000n,
    },
    {
      name: 'setConfig: 69 -> 69 signers / 3 groups',
      op: 'setConfig',
      signers: 69,
      groups: 3,
      fromSigners: 69,
      expected: 'success',
      maxGas: 900_000n,
    },
    {
      name: 'setConfig: 64 signers / 31 groups is over the current limit',
      op: 'setConfig',
      signers: 64,
      groups: 31,
      expected: 'out-of-gas',
    },
    {
      name: 'setConfig: 80 signers / 31 groups is over the single-tx limit',
      op: 'setConfig',
      signers: 80,
      groups: 31,
      expected: 'out-of-gas',
    },
    {
      name: 'setRoot: 200-signer config, 64 signatures',
      op: 'setRoot',
      signers: 200,
      groups: 31,
      signatures: 64,
      expected: 'success',
      maxGas: 860_000n,
    },
    {
      name: 'setRoot: 200-signer config, 72 signatures',
      op: 'setRoot',
      signers: 200,
      groups: 31,
      signatures: 72,
      expected: 'success',
      maxGas: 950_000n,
    },
    {
      name: 'setRoot: 200-signer config, 88 signatures is over the limit',
      op: 'setRoot',
      signers: 200,
      groups: 31,
      signatures: 88,
      expected: 'out-of-gas',
    },
    {
      name: 'execute: one op after a 64-signature root',
      op: 'execute',
      signers: 200,
      groups: 31,
      signatures: 64,
      expected: 'success',
    },
    // Team requirements. Stages larger configs; 50 non-root groups is not
    // representable because the contract supports at most 31 non-root groups.
    {
      name: 'setConfig: proposer 42 signers / 3 groups',
      op: 'setConfig',
      signers: 42,
      groups: 3,
      expected: 'success',
      maxGas: 600_000n,
    },
    {
      name: 'setConfig: proposer 42 -> 42 signers / 3 groups',
      op: 'setConfig',
      signers: 42,
      groups: 3,
      fromSigners: 42,
      expected: 'success',
      maxGas: 700_000n,
    },
    {
      name: 'setConfig: canceller 69 signers / 19 groups (staged)',
      op: 'setConfig',
      signers: 69,
      groups: 19,
      strategy: 'staged',
      expected: 'success',
    },
    {
      name: 'setConfig: canceller 32 -> 69 signers / 19 groups (staged)',
      op: 'setConfig',
      signers: 69,
      groups: 19,
      fromSigners: 32,
      strategy: 'staged',
      expected: 'success',
    },
    {
      name: 'setConfig: bypasser 69 signers / 21 groups (staged)',
      op: 'setConfig',
      signers: 69,
      groups: 21,
      strategy: 'staged',
      expected: 'success',
    },
    {
      name: 'setConfig: bypasser 32 -> 69 signers / 21 groups (staged)',
      op: 'setConfig',
      signers: 69,
      groups: 21,
      fromSigners: 32,
      strategy: 'staged',
      expected: 'success',
    },
    {
      name: 'setConfig: 150 signers / 31 groups (staged)',
      op: 'setConfig',
      signers: 150,
      groups: 31,
      strategy: 'staged',
      expected: 'success',
    },
    {
      name: 'setConfig: 200 signers / 31 groups (staged)',
      op: 'setConfig',
      signers: 200,
      groups: 31,
      strategy: 'staged',
      expected: 'success',
    },
    {
      name: 'setRoot: canceller 69 signers / 19 groups, 69 signatures',
      op: 'setRoot',
      signers: 69,
      groups: 19,
      signatures: 69,
      expected: 'success',
      maxGas: 850_000n,
    },
    {
      name: 'setRoot: bypasser 69 signers / 21 groups, 69 signatures',
      op: 'setRoot',
      signers: 69,
      groups: 21,
      signatures: 69,
      expected: 'success',
      maxGas: 850_000n,
    },
    {
      name: 'setRoot: proposer 42 signers / 3 groups, 42 signatures',
      op: 'setRoot',
      signers: 42,
      groups: 3,
      signatures: 42,
      expected: 'success',
      maxGas: 500_000n,
    },
    {
      name: 'setRoot: 150 signers / 31 groups, 72 signatures',
      op: 'setRoot',
      signers: 150,
      groups: 31,
      signatures: 72,
      expected: 'success',
      maxGas: 950_000n,
    },
  ],
})
